#!/usr/bin/env python3
"""Discover, verify, and bump ycc product version fields in lockstep.

Used by ``preflight.sh`` (``check``) and ``bump-version.sh`` (``bump``).

Discovery is a fixed, bounded list of product surfaces; the repository is never
scanned recursively, so ``ycc/mods`` (versioned separately), root dev metadata,
``node_modules`` and worktrees can never participate.

Canonical version: ``ycc/.claude-plugin/plugin.json`` ``.version`` (required).

Bumped (hand-edited sources):
  - ``ycc/.claude-plugin/plugin.json``
  - ``.claude-plugin/marketplace.json``: ``metadata.version`` and every
    ``plugins[].version`` that exists
  - ``ycc/package.json`` when it already carries a ``version``

Checked only (regenerated by ``./scripts/sync.sh``, never hand-bumped): the
marketplaces ``.agents/plugins/marketplace.json`` and
``.cursor-plugin/marketplace.json``, plus plugin and package manifests under
``.codex-plugin/`` and ``.cursor-plugin/`` (the directory and its direct child
directories), plus ``packages/<package>`` and ``packages/<runtime>/<package>``
plugin/package manifests (same bounded manifest filenames).

Missing optional files and versionless entries are valid and never gain a field.
"""

from __future__ import annotations

import json
import os
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

PLUGIN_REL = "ycc/.claude-plugin/plugin.json"
SOURCE_MARKETPLACE_REL = ".claude-plugin/marketplace.json"
OPTIONAL_MARKETPLACES = (".agents/plugins/marketplace.json", ".cursor-plugin/marketplace.json")
MANIFEST_SUBDIRS = (".opencode-plugin", ".codex-plugin", ".cursor-plugin")
EXCLUDED_NAME = "ycc-mods"
EXCLUDED_SOURCE_PREFIX = "ycc/mods"
PACKAGE_RUNTIMES = ("claude", "codex", "cursor", "opencode", "agents")
Key = str | int


class ReleaseError(Exception):
    """A discovery, parse, or write problem attributable to one or more files."""


@dataclass(frozen=True)
class VersionField:
    rel: str
    label: str
    keys: tuple[Key, ...]
    value: str


@dataclass
class Surface:
    rel: str
    data: Any
    fields: list[VersionField] = field(default_factory=list)
    mutable: bool = True


def _load(root: Path, rel: str) -> Any:
    path = root / rel
    try:
        resolved = path.resolve(strict=True)
        resolved.relative_to(root.resolve())
    except FileNotFoundError as exc:
        raise ReleaseError(f"{rel}: file not found") from exc
    except (OSError, ValueError) as exc:
        raise ReleaseError(f"{rel}: unreadable or resolves outside repository") from exc
    try:
        return json.loads(resolved.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ReleaseError(f"{rel}: invalid JSON: {exc}") from exc


def _version_field(rel: str, container: Any, keys: tuple[Key, ...], label: str) -> list[VersionField]:
    """Return a one-item list when ``container`` has a version; error if not a string."""
    if not isinstance(container, dict):
        raise ReleaseError(f"{rel}: {label.rsplit('.version', 1)[0] or 'root'}: expected object")
    if "version" not in container:
        return []
    value = container["version"]
    if not isinstance(value, str) or not value:
        raise ReleaseError(f"{rel}: {label}: expected non-empty string, got {value!r}")
    return [VersionField(rel, label, keys, value)]


def _is_excluded_entry(entry: dict[str, Any]) -> bool:
    if entry.get("name") == EXCLUDED_NAME:
        return True
    source = entry.get("source")
    if isinstance(source, dict):
        source = source.get("path")
    if isinstance(source, str):
        source = source.removeprefix("./").rstrip("/")
        return source == EXCLUDED_SOURCE_PREFIX or source.startswith(EXCLUDED_SOURCE_PREFIX + "/")
    return False


def _marketplace_surface(root: Path, rel: str, required: bool, mutable: bool) -> Surface:
    data = _load(root, rel)
    surface = Surface(rel, data, mutable=mutable)
    if not isinstance(data, dict):
        raise ReleaseError(f"{rel}: expected a JSON object")
    if "metadata" in data:
        surface.fields += _version_field(rel, data["metadata"], ("metadata", "version"), "metadata.version")
    plugins = data.get("plugins")
    if not isinstance(plugins, list) or (required and not plugins):
        raise ReleaseError(f"{rel}: plugins: expected {'non-empty ' if required else ''}array")
    for index, entry in enumerate(plugins):
        label = f"plugins[{index}].version"
        if not isinstance(entry, dict):
            raise ReleaseError(f"{rel}: plugins[{index}]: expected object")
        if _is_excluded_entry(entry):
            continue
        surface.fields += _version_field(rel, entry, ("plugins", index, "version"), label)
    return surface


def _manifest_surface(root: Path, rel: str, mutable: bool, required: bool = False) -> Surface | None:
    if not required and not (root / rel).is_file():
        return None
    data = _load(root, rel)
    if not isinstance(data, dict):
        raise ReleaseError(f"{rel}: expected a JSON object")
    if not required and data.get("name") == EXCLUDED_NAME:
        return None
    return Surface(rel, data, _version_field(rel, data, ("version",), "version"), mutable)


def _child_dirs(root: Path, rel: str) -> list[str]:
    base = root / rel
    if not base.is_dir():
        return []
    return [f"{rel}/{p.name}" for p in sorted(base.iterdir()) if p.is_dir() and p.name != EXCLUDED_NAME]


def _manifest_rels(root: Path, directory: str) -> list[str]:
    rels = [f"{directory}/{sub}/plugin.json" for sub in MANIFEST_SUBDIRS]
    return [r for r in rels + [f"{directory}/package.json"] if (root / r).is_file()]


def discover(root: Path) -> list[Surface]:
    """Return every surface; raise ReleaseError listing all file problems."""
    surfaces: list[Surface] = []
    errors: list[str] = []

    def add(builder: Any, *args: Any) -> None:
        try:
            result = builder(root, *args)
        except ReleaseError as exc:
            errors.append(str(exc))
            return
        if result is not None:
            surfaces.append(result)

    add(_manifest_surface, PLUGIN_REL, True, True)
    add(_marketplace_surface, SOURCE_MARKETPLACE_REL, True, True)
    for rel in OPTIONAL_MARKETPLACES:
        if (root / rel).is_file():
            # Regenerated by scripts/sync.sh (e.g. generate_codex_plugin.py);
            # check parity but never bump them.
            add(_marketplace_surface, rel, False, False)
    add(_manifest_surface, "ycc/package.json", True)
    package_dirs = _child_dirs(root, "packages")
    # Support both packages/<package> and packages/<runtime>/<package> layouts.
    for runtime in PACKAGE_RUNTIMES:
        package_dirs += _child_dirs(root, f"packages/{runtime}")
    for package_dir in sorted(set(package_dirs)):
        for rel in _manifest_rels(root, package_dir):
            add(_manifest_surface, rel, False)
    generated_dirs: list[str] = []
    for base in (".codex-plugin", ".cursor-plugin"):
        if (root / base).is_dir():
            generated_dirs += [base] + _child_dirs(root, base)
    for directory in generated_dirs:
        for rel in _manifest_rels(root, directory):
            add(_manifest_surface, rel, False)
    if errors:
        raise ReleaseError("\n".join(errors))
    return surfaces


def _canonical(surfaces: list[Surface]) -> str:
    for surface in surfaces:
        if surface.rel == PLUGIN_REL:
            if not surface.fields:
                raise ReleaseError(f"{PLUGIN_REL}: version: required but missing")
            return surface.fields[0].value
    raise ReleaseError(f"{PLUGIN_REL}: file not found")


def check(root: Path) -> int:
    try:
        surfaces = discover(root)
        expected = _canonical(surfaces)
    except ReleaseError as exc:
        print(str(exc), file=sys.stderr)
        return 1
    bad = [f for s in surfaces for f in s.fields if f.value != expected]
    for item in bad:
        print(f"  {item.rel} {item.label} = {item.value} (expected {expected})", file=sys.stderr)
    if bad:
        return 1
    print(expected)
    return 0


def _set(data: Any, keys: tuple[Key, ...], value: str) -> None:
    for key in keys[:-1]:
        data = data[key]
    data[keys[-1]] = value


def _serialize(data: Any) -> bytes:
    return (json.dumps(data, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def _replace(path: Path, payload: bytes) -> None:
    fd, tmp_name = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    tmp = Path(tmp_name)
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(payload)
        tmp.chmod(path.stat().st_mode & 0o7777)
        os.replace(tmp, path)
    except BaseException:
        tmp.unlink(missing_ok=True)
        raise


def bump(root: Path, new_version: str) -> int:
    try:
        surfaces = discover(root)
        _canonical(surfaces)
    except ReleaseError as exc:
        print(str(exc), file=sys.stderr)
        return 1
    plans: list[tuple[Path, bytes, bytes]] = []
    for surface in (s for s in surfaces if s.mutable):
        changed = [f for f in surface.fields if f.value != new_version]
        if not changed:
            continue
        path = root / surface.rel
        for item in changed:
            _set(surface.data, item.keys, new_version)
            print(f"{item.rel} {item.label}: {item.value} -> {new_version}")
        plans.append((path, path.read_bytes(), _serialize(surface.data)))
    written: list[tuple[Path, bytes]] = []
    try:
        for path, original, payload in plans:
            _replace(path, payload)
            written.append((path, original))
    except OSError as exc:
        for path, original in written:
            try:
                _replace(path, original)
            except OSError:
                print(f"rollback failed for {path}", file=sys.stderr)
        print(f"write failed: {exc}", file=sys.stderr)
        return 1
    return 0


def main(argv: list[str]) -> int:
    if len(argv) == 3 and argv[1] == "check":
        return check(Path(argv[2]))
    if len(argv) == 4 and argv[1] == "bump":
        return bump(Path(argv[2]), argv[3])
    print("usage: release_versions.py check <root> | bump <root> <version>", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
